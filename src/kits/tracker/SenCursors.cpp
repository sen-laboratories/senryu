const BCursor*
SenKnotCursor()
{
	static BCursor* cursor = NULL;
	if (cursor != NULL)
		return cursor;

	BBitmap bitmap(BRect(0, 0, 31, 31), B_RGBA32);
	if (bitmap.InitCheck() != B_OK)
		return NULL;

	// (not premultiplied: B_RGBA32 is B, G, R, A in memory)
	uint8* bits = (uint8*)bitmap.Bits();
	for (int32 y = 0; y < 32; y++) {
		uint8* row = bits + y * bitmap.BytesPerRow();
		for (int32 x = 0; x < 32; x++) {
			row[x * 4 + 0] = 0xc9;
			row[x * 4 + 1] = 0xc1;
			row[x * 4 + 2] = 0x3f;
			row[x * 4 + 3] = kKnotAlpha[y * 32 + x];
		}
	}

	// the middle of the knot is where the files are dropped
	BCursor* made = new BCursor(&bitmap, BPoint(16, 16));
	if (made->InitCheck() != B_OK) {
		delete made;
		return NULL;
	}
	cursor = made;
	return cursor;
}
